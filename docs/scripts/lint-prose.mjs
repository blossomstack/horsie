#!/usr/bin/env node
/**
 * Checks the documentation's frontmatter contract and its vocabulary.
 *
 * Two jobs, both mechanical:
 *
 *   1. Every page under src/content/docs declares title, description, a
 *      Diátaxis `kind`, and — inside a sidebar section — a `sidebar.order`.
 *      `astro build` already rejects a missing kind or description; this adds
 *      the ordering rule and reports all four in one place with a line number.
 *
 *   2. The framing rules in `contributing/writing-docs` that can be tested by
 *      a machine. Every rule here exists because the wording it rejects was
 *      shipped once and had to be corrected by hand.
 *
 * Scope is documentation prose: this site, plus the repo's README, which is
 * where the framing slipped before. It deliberately does NOT read DESIGN.md or
 * PRODUCT.md — those are internal design records, not documentation, and they
 * speak a different language on purpose.
 *
 * Escape hatch: wrap a region in `<!-- lint-prose-disable -->` and
 * `<!-- lint-prose-enable -->`. The writing-docs page needs it, because it has
 * to quote the words it bans.
 */

import { readFileSync } from "node:fs";
import { readdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DOCS_DIR = fileURLToPath(new URL("../src/content/docs", import.meta.url));
const REPO_ROOT = fileURLToPath(new URL("../..", import.meta.url));
const EXTRA_FILES = ["README.md"];

const KINDS = ["tutorial", "how-to", "reference", "explanation"];

/**
 * Sections whose pages are autogenerated into the sidebar, so their order is
 * frontmatter-driven and must be declared. Pages outside them (the docs home)
 * are exempt.
 */
const ORDERED_SECTIONS = [
  "start-here",
  "using",
  "operating",
  "cli",
  "internals",
  "contributing",
];

const RULES = [
  {
    id: "product-name",
    pattern: /\b(?:horsie )?session server\b/gi,
    message:
      'the product is "horsie server". Sessions are the unit of work, not the name.',
  },
  {
    id: "capitalised-name",
    pattern: /\bHorsie\b/g,
    message: 'the product name is lowercase: "horsie", including at the start of a sentence.',
  },
  {
    id: "hosted-offering",
    pattern:
      /(?<!self-)\b(?:hosted|control plane|billing|quota|quotas|tenant|multi-tenant|tenancy|fleet|SaaS|pricing)\b/gi,
    message:
      "vocabulary for a managed offering. These docs describe the software someone runs themselves.",
  },
  {
    id: "forward-looking",
    pattern:
      /\b(?:coming soon|for now,? (?:we|this) (?:only|just)|in a future release|we plan to|on the roadmap|will (?:soon|shortly)|not yet supported but)\b/gi,
    message:
      "forward-looking statement. Documentation describes what ships today; a claim written ahead of the code has had to be walked back before.",
  },
  {
    id: "vendor-agent",
    pattern: /\bvendor agents?\b/gi,
    message: 'renamed in #293 — write "vendor process".',
  },
  {
    id: "velos-as-component",
    pattern:
      /\b(?:velos-runtime|crates\/velos-runtime|(?:deploy|deploying|install|installing|run|running) velos\b)/gi,
    message:
      "velos is a vendor kind configured in Settings, not a component the reader deploys. `crates/velos-runtime` was deleted in #293.",
  },
  {
    id: "retired-config-route",
    pattern: /\bPUT \/api\/config\b/g,
    message: "retired in #292 — config is written per resource.",
  },
  {
    id: "local-runtime-framing",
    // Narrow on purpose: "a plugin could execute commands on the server host"
    // is a correct sentence. What this rejects is a *runtime* placed there.
    pattern: /\b(?:runs?|running|executes?|executing|lives?|sits?) (?:on|at) the server host\b/gi,
    message:
      "the local runtime runs on the reader's own machine and dials out. Framing it as the server host inverts the whole point.",
  },
  {
    id: "competitor",
    // Other agent harnesses are never named in these docs — not to compare
    // against, not to credit, not in passing. Capitalised on purpose: the
    // lowercase `codex` in `auth.openai.com/codex/device` is a URL a reader
    // has to type, and `.claude-plugin/` is a directory name in the bundle
    // format. Those are facts about things you configure, not references to a
    // product.
    pattern:
      /\b(?:Claude Code|OpenCode|Open Code|Codex|Cursor|Aider|Devin|Windsurf|Cline|Copilot|Goose)\b/g,
    message:
      "these docs never name another agent harness. Describe the thing itself — \"the upstream plugin specification\", \"the subscription backend\".",
  },
  {
    id: "docs-guide-path",
    pattern: /docs\/guide\//g,
    message: "that directory no longer exists — link to a page on this site.",
  },
];

const DISABLE = "<!-- lint-prose-disable -->";
const ENABLE = "<!-- lint-prose-enable -->";

/** @returns {Promise<string[]>} absolute paths of every markdown file below dir */
async function markdownFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const out = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await markdownFiles(full)));
    else if (/\.(md|mdx)$/.test(entry.name)) out.push(full);
  }
  return out.sort();
}

/**
 * Frontmatter is read with a deliberately small parser rather than a YAML
 * dependency: the contract is four scalar fields, and the failure mode of a
 * clever parser here is accepting something the build then rejects.
 */
function readFrontmatter(lines) {
  if (lines[0] !== "---") return null;
  const end = lines.indexOf("---", 1);
  if (end === -1) return null;

  const fields = new Map();
  let parent = null;
  for (let i = 1; i < end; i++) {
    const line = lines[i];
    const match = /^(\s*)([\w.-]+):\s*(.*)$/.exec(line);
    if (!match) continue;
    const [, indent, key, value] = match;
    if (indent.length === 0) {
      parent = key;
      fields.set(key, value.trim());
    } else if (parent) {
      fields.set(`${parent}.${key}`, value.trim());
    }
  }
  return { fields, bodyStart: end + 1 };
}

function checkFrontmatter(relPath, lines, problems) {
  const parsed = readFrontmatter(lines);
  if (!parsed) {
    problems.push({ file: relPath, line: 1, message: "no frontmatter block." });
    return;
  }

  const { fields } = parsed;
  const need = (key, why) => {
    const value = fields.get(key);
    if (!value || value === '""' || value === "''") {
      problems.push({ file: relPath, line: 1, message: `frontmatter is missing \`${key}\` — ${why}` });
      return null;
    }
    return value;
  };

  need("title", "it is the page heading and the sidebar label.");
  need("description", "it is the meta description and the search snippet.");

  const kind = need("kind", `one of ${KINDS.join(", ")}. See contributing/writing-docs.`);
  if (kind && !KINDS.includes(kind.replace(/["']/g, ""))) {
    problems.push({
      file: relPath,
      line: 1,
      message: `\`kind: ${kind}\` is not one of ${KINDS.join(", ")}.`,
    });
  }

  // docs/src/content/docs/<section>/<page>.md
  const section = relPath.split("/")[4];
  if (ORDERED_SECTIONS.includes(section)) {
    const order = fields.get("sidebar.order");
    if (order === undefined) {
      problems.push({
        file: relPath,
        line: 1,
        message: "frontmatter is missing `sidebar.order` — the sidebar is autogenerated, so position is the page's own to declare.",
      });
    } else if (!/^-?\d+$/.test(order)) {
      problems.push({ file: relPath, line: 1, message: `\`sidebar.order: ${order}\` is not a number.` });
    }
  }
}

function checkVocabulary(relPath, lines, problems) {
  let enabled = true;
  lines.forEach((line, index) => {
    if (line.includes(DISABLE)) enabled = false;
    if (line.includes(ENABLE)) enabled = true;
    if (!enabled) return;

    for (const rule of RULES) {
      rule.pattern.lastIndex = 0;
      const match = rule.pattern.exec(line);
      if (match) {
        problems.push({
          file: relPath,
          line: index + 1,
          message: `"${match[0]}" — ${rule.message}`,
          rule: rule.id,
        });
      }
    }
  });
}

const problems = [];
const docFiles = await markdownFiles(DOCS_DIR);

for (const file of docFiles) {
  const relPath = path.relative(REPO_ROOT, file);
  const lines = readFileSync(file, "utf8").split("\n");
  checkFrontmatter(relPath, lines, problems);
  checkVocabulary(relPath, lines, problems);
}

for (const name of EXTRA_FILES) {
  const file = path.join(REPO_ROOT, name);
  const lines = readFileSync(file, "utf8").split("\n");
  checkVocabulary(name, lines, problems);
}

if (problems.length === 0) {
  console.log(`lint-prose: ${docFiles.length + EXTRA_FILES.length} files, no problems.`);
  process.exit(0);
}

for (const problem of problems) {
  const rule = problem.rule ? ` [${problem.rule}]` : "";
  console.error(`${problem.file}:${problem.line}${rule} ${problem.message}`);
}
console.error(`\nlint-prose: ${problems.length} problem(s).`);
process.exit(1);
